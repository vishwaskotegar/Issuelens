"""Strongly-typed Pydantic schemas for evidence-backed investigation reports."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

SourceType = Literal["code", "documentation", "issue", "commit"]
ConfidenceLevel = Literal["low", "medium", "high"]
VerificationStatus = Literal["not_run", "partially_verified", "verified"]


class EvidenceItem(BaseModel):
    """An individual piece of verified evidence cited in an investigation."""

    model_config = ConfigDict(extra="ignore")

    evidence_id: str = Field(
        ...,
        description="Unique identifier for evidence item within the run (e.g. 'ev_1')",
        examples=["ev_1"],
    )
    source_type: SourceType = Field(
        ...,
        description="Type of source where evidence originated",
    )
    path_or_url: str = Field(
        ...,
        description="Repository-relative path or external canonical URL",
        examples=["requests/models.py", "https://github.com/psf/requests/issues/1234"],
    )
    start_line: int | None = Field(
        default=None,
        ge=1,
        description="1-indexed starting line number for source code citations",
    )
    end_line: int | None = Field(
        default=None,
        ge=1,
        description="1-indexed ending line number for source code citations",
    )
    excerpt: str = Field(
        ...,
        description="Exact snippet or excerpt from the pinned snapshot or document",
    )
    commit_sha: str | None = Field(
        default=None,
        description="Pinned commit SHA for repository code citations",
    )


class Hypothesis(BaseModel):
    """A testable root cause hypothesis grounded in cited evidence."""

    model_config = ConfigDict(extra="ignore")

    title: str = Field(
        ...,
        description="Brief summary title of the hypothesis",
        examples=["Unescaped URL query parameter encoding in Request.prepare_url"],
    )
    explanation: str = Field(
        ...,
        description="Technical reasoning explaining how the fault leads to the observed bug",
    )
    confidence: ConfidenceLevel = Field(
        ...,
        description="Qualitative assessment of hypothesis certainty (low | medium | high)",
    )
    confidence_rationale: str = Field(
        default="",
        description="Factual justification explaining why this confidence rating was assigned",
    )
    supporting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of evidence_id references supporting this hypothesis",
    )
    contradicting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of evidence_id references contradicting this hypothesis",
    )
    verification_steps: list[str] = Field(
        default_factory=list,
        description="Actionable steps a developer can take to verify or falsify this hypothesis",
    )


class InvestigationReportPayload(BaseModel):
    """Structured report content generated by LLM analysis."""

    model_config = ConfigDict(extra="ignore")

    summary: str = Field(
        ...,
        description="High-level synthesis of the investigated issue and primary findings",
    )
    observed_facts: list[str] = Field(
        default_factory=list,
        description="Direct facts from the issue, stack trace, or code without guessing",
    )
    hypotheses: list[Hypothesis] = Field(
        default_factory=list,
        description="Ranked list of plausible root causes grounded in evidence",
    )
    missing_information: list[str] = Field(
        default_factory=list,
        description="Key information missing from issue or repository needed for diagnosis",
    )
    suggested_tests: list[str] = Field(
        default_factory=list,
        description="Suggested regression or unit tests to reproduce and safeguard against the bug",
    )
    recommended_next_steps: list[str] = Field(
        default_factory=list,
        description="Actionable recommendations for maintainers or investigating developers",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Known constraints, assumptions, and scope boundaries of this investigation",
    )


class InvestigationReport(BaseModel):
    """Complete, evidence-backed investigation report for a GitHub bug report."""

    model_config = ConfigDict(extra="ignore")

    run_id: str = Field(
        ...,
        description="Unique investigation run identifier",
        examples=["inv_abc123def456"],
    )
    issue_url: str = Field(
        ...,
        description="Canonical URL of the investigated GitHub issue",
        examples=["https://github.com/psf/requests/issues/1234"],
    )
    repository: str = Field(
        ...,
        description="Repository coordinate: owner/repo",
        examples=["psf/requests"],
    )
    commit_sha: str = Field(
        ...,
        description="Pinned 40-char commit SHA representing investigated repository snapshot",
        examples=["abcdef1234567890abcdef1234567890abcdef12"],
    )
    summary: str = Field(
        ...,
        description="High-level synthesis of the investigated issue and primary findings",
    )
    observed_facts: list[str] = Field(
        default_factory=list,
        description="Direct facts from the issue, stack trace, or code without guessing",
    )
    hypotheses: list[Hypothesis] = Field(
        default_factory=list,
        description="Ranked list of plausible root causes grounded in evidence",
    )
    evidence: list[EvidenceItem] = Field(
        default_factory=list,
        description="Complete list of evidence items cited across hypotheses",
    )
    missing_information: list[str] = Field(
        default_factory=list,
        description="Key information missing from issue or repository needed for diagnosis",
    )
    suggested_tests: list[str] = Field(
        default_factory=list,
        description="Suggested regression or unit tests to reproduce and safeguard against the bug",
    )
    recommended_next_steps: list[str] = Field(
        default_factory=list,
        description="Actionable recommendations for maintainers or investigating developers",
    )
    verification_status: VerificationStatus = Field(
        default="not_run",
        description="Verification state of investigation. Repository tests are never run in MVP.",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Known constraints, assumptions, and scope boundaries of this investigation",
    )

    @classmethod
    def from_payload(
        cls,
        payload: InvestigationReportPayload,
        run_id: str,
        issue_url: str,
        repository: str,
        commit_sha: str,
        evidence: list[EvidenceItem],
    ) -> "InvestigationReport":
        """Construct validated report by binding LLM analysis with verified snapshot provenance."""
        return cls(
            run_id=run_id,
            issue_url=issue_url,
            repository=repository,
            commit_sha=commit_sha,
            evidence=evidence,
            summary=payload.summary,
            observed_facts=payload.observed_facts,
            hypotheses=payload.hypotheses,
            missing_information=payload.missing_information,
            suggested_tests=payload.suggested_tests,
            recommended_next_steps=payload.recommended_next_steps,
            verification_status="not_run",
            limitations=payload.limitations,
        )
